# ============================================================
# SMOOTHSTEP
# ============================================================

def smoothstep(t):

    return (
        3 * t**2
        - 2 * t**3
    )


# ============================================================
# FORMATION TRANSITION
# ============================================================

def create_transition(
    X_start,
    target_start,
    target_end,
    current_letter
):

    X_current = X_start.copy()


    for frame in range(frames_per_letter):

        # ----------------------------------------------------
        # Normalized time
        # ----------------------------------------------------

        t = frame / (
            frames_per_letter - 1
        )


        # ----------------------------------------------------
        # Smooth movement
        # ----------------------------------------------------

        s = smoothstep(t)


        # ----------------------------------------------------
        # Desired intermediate formation
        # ----------------------------------------------------

        desired = (
            (1 - s) * target_start
            + s * target_end
        )


        # ----------------------------------------------------
        # Formation control
        # ----------------------------------------------------

        control = np.zeros(
            (N, 2)
        )


        for i in range(N):

            # -----------------------------------------------
            # Attraction toward target
            # -----------------------------------------------

            control[i] += (
                k_target
                * (
                    desired[i]
                    - X_current[i]
                )
            )


            # -----------------------------------------------
            # Graph-based coordination
            # -----------------------------------------------

            for j in G_graph.neighbors(i):

                error = (
                    (
                        desired[i]
                        - desired[j]
                    )
                    -
                    (
                        X_current[i]
                        - X_current[j]
                    )
                )


                control[i] += (
                    k_graph
                    * error
                )


        # ----------------------------------------------------
        # Update position
        # ----------------------------------------------------

        X_current = (
            X_current
            + dt * control
        )


        # ----------------------------------------------------
        # Make final frame exactly equal to target
        # ----------------------------------------------------

        if frame == frames_per_letter - 1:

            X_current = target_end.copy()


        # ----------------------------------------------------
        # Save frame
        # ----------------------------------------------------

        trajectory.append(
            X_current.copy()
        )


        trajectory_letters.append(
            current_letter
        )


    return X_current


