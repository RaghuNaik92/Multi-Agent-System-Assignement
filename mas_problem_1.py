def update(frame):

    # --------------------------------------------------------
    # Current positions
    # --------------------------------------------------------

    positions = trajectory[frame]


    # --------------------------------------------------------
    # Move agents
    # --------------------------------------------------------

    agents.set_offsets(
        positions
    )


    # --------------------------------------------------------
    # Move agent numbers
    # --------------------------------------------------------

    for i in range(N):

        agent_labels[i].set_position(
            (
                positions[i, 0] + 0.06,
                positions[i, 1] + 0.06
            )
        )


    # ========================================================
    # CURRENT LETTER
    # ========================================================

    letter_index = (
        frame // frames_per_letter
    )


    # Safety check

    letter_index = min(
        letter_index,
        len(letters) - 1
    )


    current_letter = letters[
        letter_index
    ]


    # --------------------------------------------------------
    # Change large letter
    # --------------------------------------------------------

    letter_text.set_text(
        current_letter
    )


    # --------------------------------------------------------
    # Change formation number
    # --------------------------------------------------------

    progress_text.set_text(
        f"Formation {letter_index + 1} / 5"
    )


    return (
        [agents]
        + agent_labels
        + [
            letter_text,
            progress_text
        ]
    )


